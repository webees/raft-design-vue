#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(root, "../src");
const themes = JSON.parse(await readFile(path.join(src, "themes.json"), "utf8"));

function declarations(tokens, indent = "  ") {
  return Object.entries(tokens)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join("\n");
}

function themeBlock(selector, tokens) {
  return `${selector} {\n${declarations(tokens)}\n}`;
}

const blocks = [
  "/* Generated by scripts/build-themes.mjs from src/themes.json. Do not edit. */",
  "/* Agent sprite decor is intentionally excluded: brand artwork is not part of this package. */",
];

for (const [name, theme] of Object.entries(themes.themes)) {
  const attr = `[data-theme="${name}"]`;
  blocks.push(
    themeBlock(`.light${attr}`, theme.light),
    themeBlock(`:root:not(.light):not(.dark)${attr}`, theme.light),
    themeBlock(`.dark${attr}`, theme.dark),
    `@media (prefers-color-scheme: dark) {\n${themeBlock(
      `:root:not(.light):not(.dark)${attr}`,
      theme.dark,
    )}\n}`,
  );
}

await writeFile(path.join(src, "themes.css"), `${blocks.join("\n\n")}\n`, "utf8");
console.log(`themes.css: ${Object.keys(themes.themes).length} themes`);
